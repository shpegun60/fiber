"""Pure recorder controls; fake tools never execute a compiler or target."""
import hashlib
import importlib.util
import json
from pathlib import Path
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import Mock

sys.dont_write_bytecode = True
source = Path(__file__).with_name('probe.py')
spec = importlib.util.spec_from_file_location('cm3_lto_capture_pure_controls', source)
p = importlib.util.module_from_spec(spec)
spec.loader.exec_module(p)


class Watch:
    def __init__(self):
        self.hashes = {}

    def read(self, path):
        path = Path(path)
        data = path.read_bytes()
        digest = hashlib.sha256(data).hexdigest().upper()
        if path in self.hashes and self.hashes[path] != digest:
            raise ValueError('watched generated bytes changed')
        self.hashes[path] = digest
        return data

    def structured(self, path):
        return json.loads(self.read(path))


class RecorderTests(unittest.TestCase):
    def fixture(self, root):
        probe = p.Probe.__new__(p.Probe)
        probe.output = root
        probe.sha = lambda data: hashlib.sha256(data).hexdigest().upper()
        probe.watch = Watch()
        def save(path, data):
            Path(path).write_text(json.dumps(data, sort_keys=True), encoding='ascii')
        def same(actual, expected, label):
            if actual != expected:
                raise ValueError(label)
        probe.api = SimpleNamespace(save=save, same=same, unique_object=dict,
            files_under=lambda root: {path.relative_to(root).as_posix(): path for path in root.rglob('*') if path.is_file()})
        probe.report = dict(Status='FAIL')
        probe.admission = SimpleNamespace(identities={}, close=Mock(),
            identity=lambda path: (Path(path).stat().st_ino, Path(path).stat().st_size))
        return probe

    def test_pins_consumed_bytes_before_later_manifest(self):
        with tempfile.TemporaryDirectory() as directory:
            probe = self.fixture(Path(directory))
            path = probe.output / 'image.elf'
            path.write_bytes(b'not an ELF; synthetic generated bytes')
            probe.pin_generated(path)
            path.write_bytes(b'changed generated bytes')
            with self.assertRaisesRegex(ValueError, 'generated bytes changed'):
                probe.pin_generated(path)

    def test_generated_paths_cannot_escape_output(self):
        with tempfile.TemporaryDirectory() as directory:
            probe = self.fixture(Path(directory))
            with self.assertRaisesRegex(ValueError, 'outside new output'):
                probe.pin_generated(probe.output.parent / 'not-read.bin')

    def test_generated_physical_identity_drift_rejects(self):
        with tempfile.TemporaryDirectory() as directory:
            probe = self.fixture(Path(directory))
            path = probe.output / 'result.bin'
            path.write_bytes(b'data')
            probe.pin_generated(path)
            probe.admission.identity = lambda path: ('different identity', 4)
            with self.assertRaisesRegex(ValueError, 'physical identity changed'):
                probe.pin_generated(path)

    def test_closing_drift_is_not_hidden_by_expected_tool_failure(self):
        with tempfile.TemporaryDirectory() as directory:
            probe = self.fixture(Path(directory))
            probe.admission.close.side_effect = [None, ValueError('closing drift')]
            tools = SimpleNamespace(report=dict(Commands=[]))
            def command(argv, label, **kwargs):
                record = dict(Label=label, Exit=1, Status='FAIL', TimedOut=False)
                tools.report['Commands'].append(record)
                probe.api.save(probe.output / 'command-0000.json', record)
                (probe.output / 'command-0000.stdout').write_bytes(b'')
                (probe.output / 'command-0000.stderr').write_bytes(b'multiple definition of SVC_Handler')
                raise ValueError('cm3-lto-probe: command failed/timeout: ' + label)
            tools.command = command
            probe.tools = tools
            with self.assertRaisesRegex(ValueError, '^closing drift$'):
                probe.command(['fake tool; never executed'], 'link intended conflict SVC_Handler')
            self.assertEqual(len(probe.watch.hashes), 3)

    def test_late_manifest_change_rejects(self):
        with tempfile.TemporaryDirectory() as directory:
            probe = self.fixture(Path(directory))
            probe.admission.close.side_effect = lambda: (probe.output / 'artifacts.json').write_bytes(b'changed manifest')
            with self.assertRaisesRegex(ValueError, 'manifest drift'):
                probe.seal()

    def test_successful_seal_binds_receipt(self):
        with tempfile.TemporaryDirectory() as directory:
            probe = self.fixture(Path(directory))
            probe.seal()
            manifest = json.loads((probe.output / 'artifacts.json').read_bytes())
            self.assertEqual(manifest['Artifacts']['results.json'], probe.sha((probe.output / 'results.json').read_bytes()))


if __name__ == '__main__':
    unittest.main()
