#include "fiber_port_private.h"
#define POLICY(x) FIBER_STATIC_ASSERT((x), "C55S default policy: " #x)
POLICY(FIBER_FPU_LAZY == 0);
POLICY(FIBER_REWIND_MSP == 1);
POLICY(FIBER_VALIDATE_BOOT_RECORD_HASH_ON_SWITCH == 1);
POLICY(FIBER_VALIDATE_ADDRESS_MAP_ON_SWITCH == 0);
POLICY(FIBER_ALLOW_PERMISSIVE_ADDRESS_MAP_HOOKS == 0);
POLICY(FIBER_STACK_CANARY == 1);
POLICY(FIBER_STACK_REDZONE_BYTES == 32u);
POLICY(FIBER_PORT_SCHEDULER_BASEPRI == (__NVIC_PRIO_BITS == 8 ? 2u : 1u << (8u - __NVIC_PRIO_BITS)));
POLICY(FIBER_PORT_RUNTIME_SELECTABLE == 0);
__attribute__((used, externally_visible, section(".proof_roots")))
const uint32_t c55s_default_policy[9] = {
    FIBER_FPU_LAZY, FIBER_REWIND_MSP, FIBER_VALIDATE_BOOT_RECORD_HASH_ON_SWITCH,
    FIBER_VALIDATE_ADDRESS_MAP_ON_SWITCH, FIBER_ALLOW_PERMISSIVE_ADDRESS_MAP_HOOKS,
    FIBER_STACK_CANARY, FIBER_STACK_REDZONE_BYTES, FIBER_PORT_SCHEDULER_BASEPRI,
    FIBER_PORT_RUNTIME_SELECTABLE
};
