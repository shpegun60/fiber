class Closure:
    """Generated bytes only, with physical hash and membership closing checks."""

    def __init__(self):
        self.hashes, self.memberships = {}, {}
        self.identities, self.denied = {}, {REPO}
        self.buffers, self.close_readers = {}, []
        self.close_calls = 0
        self.fail_on_close = None

    def read(self, path, expected=None):
        path = Path(path)
        raw = path.read_bytes()
        digest = sha(raw)
        if expected is not None and digest != expected:
            raise ValueError("synthetic expected input hash mismatch")
        if path in self.hashes and self.hashes[path] != digest:
            raise ValueError("synthetic input closing drift")
        value = path.stat()
        identity = (value.st_dev, value.st_ino, value.st_nlink, value.st_size)
        if path in self.identities and self.identities[path] != identity:
            raise ValueError("synthetic physical identity drift")
        self.hashes[path] = digest
        self.identities[path] = identity
        if path.suffix == ".py":
            self.buffers[path] = raw
        return raw

    def structured(self, path, expected=None):
        return json.loads(self.read(path, expected))

    def tree(self, root, expected):
        root = Path(root)
        actual = {p.relative_to(root).as_posix(): p for p in root.rglob("*") if p.is_file()}
        if set(actual) != set(expected):
            raise ValueError("synthetic input membership mismatch")
        self.memberships[root] = set(expected)
        for name, path in actual.items():
            self.read(path, expected[name])

    def close(self):
        self.close_calls += 1
        self.close_readers.append(Path.read_bytes)
        if self.close_calls == self.fail_on_close:
            raise ValueError("synthetic late closing failure")
        for path, digest in tuple(self.hashes.items()):
            self.read(path, digest)
        for root, names in self.memberships.items():
            if {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()} != names:
                raise ValueError("synthetic late input membership drift")


